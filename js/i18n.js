// ----- i18n Engine -----
class I18n {
  constructor() {
    this.currentLang = localStorage.getItem('jexa-lang') || 'vi';
    this.listeners = [];
  }

  t(key) {
    const dict = translations[this.currentLang];
    return dict && dict[key] ? dict[key] : key;
  }

  setLang(lang) {
    if (lang === this.currentLang) return;
    this.currentLang = lang;
    localStorage.setItem('jexa-lang', lang);
    this.updateDOM();
    this.notifyListeners();
  }

  getLang() {
    return this.currentLang;
  }

  toggleLang() {
    this.setLang(this.currentLang === 'vi' ? 'en' : 'vi');
  }

  updateDOM() {
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation !== key) {
        el.textContent = translation;
      }
    });

    // Update elements with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation !== key) {
        el.setAttribute('placeholder', translation);
      }
    });

    // Update elements with data-i18n-html (for HTML content)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const translation = this.t(key);
      if (translation !== key) {
        el.innerHTML = translation;
      }
    });

    // Update lang attribute on html
    document.documentElement.lang = this.currentLang;

    // Update lang switcher buttons
    document.querySelectorAll('.lang-switch__btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === this.currentLang);
    });
  }

  onLangChange(callback) {
    this.listeners.push(callback);
  }

  notifyListeners() {
    this.listeners.forEach(cb => cb(this.currentLang));
  }

  init() {
    this.updateDOM();

    // Bind language switcher buttons
    document.querySelectorAll('.lang-switch__btn').forEach(btn => {
      btn.addEventListener('click', () => {
        this.setLang(btn.dataset.lang);
      });
    });
  }
}

// Export singleton
window.i18n = new I18n();
